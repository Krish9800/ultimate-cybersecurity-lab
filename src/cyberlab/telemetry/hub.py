"""Unified defensive telemetry and detection evaluation hub."""

from cyberlab.models.campaign import AttackScenario, StepExecutionResult
from cyberlab.models.enums import AttackStatus, DetectionOutcome
from cyberlab.models.telemetry import (
    DetectionAlert,
    DetectionEvaluation,
    SensorEvent,
)
from cyberlab.telemetry.rules import DetectionRuleEngine
from cyberlab.telemetry.sensors import TelemetrySynthesizer
from cyberlab.topology.engine import VirtualTopologyEngine


class TelemetryHub:
    """Aggregates telemetry from sensors, evaluates detection rules, and scores coverage."""

    def __init__(self, rule_engine: DetectionRuleEngine | None = None) -> None:
        """Initialize telemetry hub with optional custom rule engine."""
        self._rule_engine = rule_engine or DetectionRuleEngine()
        self._events: list[SensorEvent] = []
        self._alerts: list[DetectionAlert] = []

    @property
    def rule_engine(self) -> DetectionRuleEngine:
        """Access detection rule engine."""
        return self._rule_engine

    @property
    def events(self) -> list[SensorEvent]:
        """Chronological sensor events ingested."""
        return list(self._events)

    @property
    def alerts(self) -> list[DetectionAlert]:
        """All alerts generated by detection rules."""
        return list(self._alerts)

    def clear(self) -> None:
        """Reset hub telemetry and alerts."""
        self._events.clear()
        self._alerts.clear()

    def ingest_event(self, event: SensorEvent) -> list[DetectionAlert]:
        """Ingest single sensor event, evaluate against rules, and record alerts."""
        self._events.append(event)
        new_alerts = self._rule_engine.evaluate_event(event)
        self._alerts.extend(new_alerts)
        return new_alerts

    def ingest_campaign_results(
        self,
        scenario: AttackScenario,
        results: list[StepExecutionResult],
        topology: VirtualTopologyEngine,
    ) -> DetectionEvaluation:
        """Synthesize telemetry for campaign steps and evaluate defensive detection."""
        step_map = {s.step_id: s for s in scenario.steps}

        for res in results:
            step = step_map.get(res.step_id)
            if not step:
                continue
            step_events = TelemetrySynthesizer.synthesize_step_telemetry(step, res, topology)
            for evt in step_events:
                self.ingest_event(evt)

        return self.evaluate_detection(results)

    def evaluate_detection(
        self,
        results: list[StepExecutionResult],
    ) -> DetectionEvaluation:
        """Correlate attack steps with generated alerts and compute metrics."""
        step_outcomes: dict[str, DetectionOutcome] = {}
        detection_latencies: list[float] = []

        detected_count = 0
        blocked_count = 0
        missed_count = 0
        partial_count = 0

        for step_res in results:
            if step_res.status == AttackStatus.BLOCKED:
                step_outcomes[step_res.step_id] = DetectionOutcome.BLOCKED
                blocked_count += 1
                continue

            # Look for correlated alerts by technique and timestamp window
            matched_alerts = [
                a
                for a in self._alerts
                if a.mitre_technique_id == step_res.technique_id
                and (step_res.start_time - 0.5 <= a.timestamp <= step_res.end_time + 2.0)
            ]

            if matched_alerts:
                step_outcomes[step_res.step_id] = DetectionOutcome.DETECTED
                detected_count += 1
                # Latency from step start to first alert
                first_alert = min(matched_alerts, key=lambda a: a.timestamp)
                latency = max(0.01, first_alert.timestamp - step_res.start_time)
                detection_latencies.append(latency)
            else:
                step_outcomes[step_res.step_id] = DetectionOutcome.MISSED
                missed_count += 1

        total = len(results)
        coverage_rate = ((detected_count + blocked_count) / total) * 100.0 if total > 0 else 0.0

        mttd = sum(detection_latencies) / len(detection_latencies) if detection_latencies else 0.0

        return DetectionEvaluation(
            total_steps=total,
            detected_count=detected_count,
            blocked_count=blocked_count,
            missed_count=missed_count,
            partial_count=partial_count,
            detection_coverage_rate=round(coverage_rate, 2),
            mean_time_to_detect=round(mttd, 3),
            alerts=list(self._alerts),
            step_outcomes=step_outcomes,
        )
